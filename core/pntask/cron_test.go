func TestParseErrors(t *testing.T) {
	tests := []struct {
		spec string
		want string // 错误信息里应当出现的文字
	}{
		{"", "应当有 6 段"},
		{"* * * * *", "实际有 5 段"},
		{"* * * * * * *", "实际有 7 段"},
		{"60 * * * * *", "第 1 段（秒）"},
		{"* 60 * * * *", "第 2 段（分）"},
		{"* * 24 * * *", "第 3 段（时）"},
		{"* * * 0 * *", "第 4 段（日）"},
		{"* * * 32 * *", "第 4 段（日）"},
		{"* * * * 0 *", "第 5 段（月）"},
		{"* * * * 13 *", "第 5 段（月）"},
		{"* * * * * 8", "第 6 段（周）"},
		{"x * * * * *", "不是数字"},
		{"1-x * * * * *", "不是数字"},
		{"5-1 * * * * *", "取值范围"},
		{"*/0 * * * * *", "步长"},
		{"*/x * * * * *", "步长"},
		{"1,,2 * * * * *", "不是数字"},
		{"* * * * jan *", "不是数字"},
		{"-1 * * * * *", "不是数字"},
	}
	for _, tt := range tests {
		if _, err := parse(tt.spec); err == nil || !strings.Contains(err.Error(), tt.want) {
			t.Errorf("parse(%q) 应当返回包含 %q 的错误，得到 %v", tt.spec, tt.want, err)
		}
	}
}

func TestNext(t *testing.T) {
	const layout = "2006-01-02 15:04:05"
	tests := []struct {
		name string
		spec string
		from string
		want string // 空串表示五年内不会触发
	}{
		{"每秒", "* * * * * *", "2026-11-11 10:00:00", "2026-11-11 10:00:01"},
		{"每秒：跨分钟", "* * * * * *", "2026-11-11 10:00:59", "2026-11-11 10:01:00"},
		{"每秒：跨年", "* * * * * *", "2026-12-31 23:59:59", "2027-01-01 00:00:00"},
		{"每分钟的第 0 秒", "0 * * * * *", "2026-11-11 10:00:00", "2026-11-11 10:01:00"},
		{"每分钟的第 0 秒：从半中间起", "0 * * * * *", "2026-11-11 10:00:30", "2026-11-11 10:01:00"},
		{"每 10 秒", "*/10 * * * * *", "2026-11-11 10:00:05", "2026-11-11 10:00:10"},
		{"每 10 秒：跨分钟", "*/10 * * * * *", "2026-11-11 10:00:50", "2026-11-11 10:01:00"},
		{"每 15 分钟", "0 */15 * * * *", "2026-11-11 10:46:00", "2026-11-11 11:00:00"},
		{"范围加步长", "0 10-40/10 * * * *", "2026-11-11 10:20:00", "2026-11-11 10:30:00"},
		{"范围加步长：过了范围到下一小时", "0 10-40/10 * * * *", "2026-11-11 10:40:00", "2026-11-11 11:10:00"},
		{"从 5 起每 15 一步", "5/15 * * * * *", "2026-11-11 10:00:20", "2026-11-11 10:00:35"},
		{"从 5 起每 15 一步：到 50 为止", "5/15 * * * * *", "2026-11-11 10:00:50", "2026-11-11 10:01:05"},
		{"列表", "0 0 8,12,18 * * *", "2026-11-11 12:00:00", "2026-11-11 18:00:00"},
		{"列表：跨天", "0 0 8,12,18 * * *", "2026-11-11 18:00:00", "2026-11-12 08:00:00"},
		{"每天 3 点", "0 0 3 * * *", "2026-11-11 10:00:00", "2026-11-12 03:00:00"},
		{"每天 3 点：当天还没到", "0 0 3 * * *", "2026-11-11 02:59:59", "2026-11-11 03:00:00"},
		{"每月 1 日", "0 0 0 1 * *", "2026-11-11 10:00:00", "2026-12-01 00:00:00"},
		{"每月 31 日：跳过小月", "0 0 0 31 * *", "2026-11-11 10:00:00", "2026-12-31 00:00:00"},
		{"每月 31 日：跨年", "0 0 0 31 * *", "2026-12-31 00:00:00", "2027-01-31 00:00:00"},
		{"每年 1 月 1 日", "0 0 0 1 1 *", "2026-11-11 10:00:00", "2027-01-01 00:00:00"},
		{"闰年 2 月 29 日", "0 0 0 29 2 *", "2026-11-11 10:00:00", "2028-02-29 00:00:00"},
		{"月份范围", "0 0 0 1 3-5 *", "2026-05-01 00:00:00", "2027-03-01 00:00:00"},
		{"周一到周五 9 点半：周三起", "0 30 9 * * 1-5", "2026-11-11 10:00:00", "2026-11-12 09:30:00"},
		{"周一到周五 9 点半：周五起跳到周一", "0 30 9 * * 1-5", "2026-11-13 09:30:00", "2026-11-16 09:30:00"},
		{"周日写 0", "0 0 0 * * 0", "2026-11-11 10:00:00", "2026-11-15 00:00:00"},
		{"周日写 7", "0 0 0 * * 7", "2026-11-11 10:00:00", "2026-11-15 00:00:00"},
		{"周六和周日", "0 0 0 * * 6-7", "2026-11-11 10:00:00", "2026-11-14 00:00:00"},
		{"日和周都写了：任意一段对上就算（15 日先到）", "0 0 0 15 * 1", "2026-11-14 00:00:00", "2026-11-15 00:00:00"},
		{"日和周都写了：任意一段对上就算（周一先到）", "0 0 0 15 * 1", "2026-11-15 00:00:00", "2026-11-16 00:00:00"},
		{"只写了周：日是 * 不参与", "0 0 0 * * 1", "2026-11-11 10:00:00", "2026-11-16 00:00:00"},
		{"日带步长也算 *：要和周同时对上（15 日是周日，16 日是双数）", "0 0 9 */2 * 1-5", "2026-11-14 10:00:00", "2026-11-17 09:00:00"},
		{"周带步长也算 *：要和日同时对上（12 日周四不是 15 日）", "0 0 0 15 * */2", "2026-11-11 10:00:00", "2026-11-15 00:00:00"},
		{"周带步长也算 *：下一个既是 15 日、又在周日二四六的日子", "0 0 0 15 * */2", "2026-11-15 00:00:00", "2026-12-15 00:00:00"},
		{"带纳秒的起点：结果是整秒", "* * * * * *", "2026-11-11 10:00:00.5", "2026-11-11 10:00:01"},
		{"2 月 30 日永远不会到", "0 0 0 30 2 *", "2026-11-11 10:00:00", ""},
		{"4 月 31 日永远不会到", "0 0 0 31 4 *", "2026-11-11 10:00:00", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			s, err := parse(tt.spec)
			if err != nil {
				t.Fatal(err)
			}
			from, err := time.ParseInLocation(layout, tt.from, time.Local)
			if err != nil {
				t.Fatal(err)
			}
			got := s.next(from)
			if tt.want == "" {
				if !got.IsZero() {
					t.Errorf("next = %s，期望零值", got.Format(layout))
				}
				return
			}
			if got.Format(layout) != tt.want || got.Nanosecond() != 0 || got.Location() != time.Local {
				t.Errorf("next(%s) = %s，期望 %s", tt.from, got.Format(time.RFC3339Nano), tt.want)
			}
			if !got.After(from) {
				t.Errorf("结果必须严格晚于起点")
			}
		})
	}
}

// 有夏令时的时区：在切换点前后也要一直往前走，不能原地打转。
func TestNextAcrossDST(t *testing.T) {
	ny, err := time.LoadLocation("America/New_York")
	if err != nil {
		t.Skipf("本机没有时区数据库，跳过：%v", err)
	}
	for _, spec := range []string{"0 30 2 * * *", "0 0 * * * *", "0 0 0 * * *", "*/30 * * * * *", "0 0 3 8 3 *"} {
		s, err := parse(spec)
		if err != nil {
			t.Fatal(err)
		}
		// 2026-03-08 02:00 拨快一小时，2026-11-01 02:00 拨慢一小时
		for _, from := range []time.Time{
			time.Date(2026, 3, 7, 23, 0, 0, 0, ny),
			time.Date(2026, 3, 8, 1, 59, 59, 0, ny),
			time.Date(2026, 10, 31, 23, 0, 0, 0, ny),
			time.Date(2026, 11, 1, 1, 30, 0, 0, ny),
		} {
			cur := from
			for i := range 200 {
				n := s.next(cur)
				if n.IsZero() || !n.After(cur) {
					t.Fatalf("%q 从 %s 起第 %d 步没有前进：%s", spec, from, i, n)
				}
				cur = n
			}
		}
	}
}
